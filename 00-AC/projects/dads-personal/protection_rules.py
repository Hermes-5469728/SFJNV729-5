def query_protection_rules(scenario_desc: str) -> list | None:
    endpoint = f"/knowledge/protection/{scenario_desc[:30]}"
    _client.read_data(endpoint)

    tokens = set(scenario_desc.lower().replace("\uff0c", " ").replace(",", " ").split())

    scored = []
    for rule in PROTECTION_KB:
        rule_tokens = set(k.lower() for k in rule["risk_keywords"])
        match_count = len(tokens & rule_tokens)
        if match_count == 0:
            continue
        coverage = match_count / len(rule["risk_keywords"])
        specificity = match_count / len(tokens) if tokens else 0
        score = 0.6 * coverage + 0.4 * specificity
        scored.append((score, rule))

    scored.sort(key=lambda x: x[0], reverse=True)
    return [r for _, r in scored] if scored else None
